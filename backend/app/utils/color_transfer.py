import cv2
import numpy as np

def apply_color_transfer(target: np.ndarray, reference: np.ndarray, strength: float = 0.3) -> np.ndarray:
    """
    Applies Reinhard color transfer from the reference image to the target image in LAB color space.
    Matches the mean and standard deviation of the A and B channels only, blending with the target.
    Helps correct flat/wrong colors (like black foliage) generated by blind colorizers.
    """
    # Convert both to LAB
    target_lab = cv2.cvtColor(target, cv2.COLOR_BGR2LAB).astype(np.float32)
    reference_lab = cv2.cvtColor(reference, cv2.COLOR_BGR2LAB).astype(np.float32)

    # Compute mean and stddev for target
    t_mean, t_std = cv2.meanStdDev(target_lab)
    t_mean = t_mean.flatten()
    t_std = t_std.flatten()

    # Compute mean and stddev for reference
    r_mean, r_std = cv2.meanStdDev(reference_lab)
    r_mean = r_mean.flatten()
    r_std = r_std.flatten()

    # Prevent division by zero
    t_std = np.where(t_std == 0, 1.0, t_std)

    # Transfer color A and B channels (indices 1 and 2)
    transferred_lab = target_lab.copy()
    for i in range(1, 3):
        transferred_lab[:, :, i] = ((target_lab[:, :, i] - t_mean[i]) * (r_std[i] / t_std[i])) + r_mean[i]

    # Blend with original
    target_lab[:, :, 1:] = (1 - strength) * target_lab[:, :, 1:] + strength * transferred_lab[:, :, 1:]

    # Clip values to valid LAB range and convert back to BGR
    target_lab = np.clip(target_lab, 0, 255).astype(np.uint8)
    return cv2.cvtColor(target_lab, cv2.COLOR_LAB2BGR)
